/// `name` (as collected by the facts walker: unquoted parts lowercased) is a pure built-in of `engine`.
pub fn is_pure(engine: Engine, name: &str) -> bool {
    let specific = match engine {
        Engine::Pg => PG,
        Engine::Mysql => MYSQL,
        Engine::Sqlite => SQLITE,
        Engine::Mongo => &[],
    };
    COMMON.contains(&name) || specific.contains(&name)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Functions that write, lock, sleep, touch files, change settings or reach other servers.
    /// None of them may ever be added to a list.
    const NEVER: &[&str] = &[
        "pg_terminate_backend",
        "pg_cancel_backend",
        "pg_reload_conf",
        "pg_sleep",
        "pg_sleep_for",
        "pg_sleep_until",
        "set_config",
        "pg_advisory_lock",
        "pg_try_advisory_lock",
        "pg_advisory_xact_lock",
        "nextval",
        "setval",
        "lo_import",
        "lo_export",
        "pg_read_file",
        "pg_read_binary_file",
        "pg_ls_dir",
        "dblink",
        "dblink_exec",
        "pg_notify",
        "txid_current",
        "current_setting",
        "sleep",
        "benchmark",
        "get_lock",
        "release_lock",
        "load_file",
        "last_insert_id",
        "load_extension",
        "readfile",
        "writefile",
        "edit",
        "fts3_tokenizer",
        "changes",
    ];

    #[test]
    fn no_side_effect_function_is_listed() {
        for f in NEVER {
            for e in [Engine::Pg, Engine::Mysql, Engine::Sqlite] {
                assert!(!is_pure(e, f), "{f} is listed for {e:?}");
            }
        }
    }

    #[test]
    fn lists_are_lowercase_and_unqualified() {
        for f in COMMON.iter().chain(PG).chain(MYSQL).chain(SQLITE) {
            assert_eq!(*f, f.to_lowercase(), "{f}");
            assert!(!f.contains('.'), "{f}");
        }
    }
}
